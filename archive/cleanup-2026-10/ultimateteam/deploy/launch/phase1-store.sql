-- Aurora 21 phase-1 store (pack-odds-2026-09/PLAN.md v2 section 3.3; owner decisions 2026-09-29). Runs after
-- launch-store.sql, on the launch store: the six standard packs draw the phase pool by rating band (migration 068,
-- rules/pack_odds.json), Gold and Premium Gold hold players only, and a 25,000-coin Rare Gold Pack (12 rare gold players)
-- joins them, with a 3,000-coin Consumables Pack. Half of a bronze or silver pack's manager hits are a manager league card
-- (migration 071). Prices stay as launch-store.sql set them; FIFA Points are not sold (coins only).
--
-- Pack bios carry no odds (owner decision D15): the odds are published outside the game, generated by the calculator.
--
-- Run once, on the production database, after the predeploy dump and after the image with migration 071 is live (see
-- README.md in this folder). It is not a migration: the store is operator data. It stops without changing anything
-- unless the launch store is what it finds.
BEGIN;

DO $$
BEGIN
    IF (SELECT count(*) FROM ultimateteam.store_packs WHERE kind = 'store' AND pack_id IN (1, 2, 3, 4, 5, 6)
            AND size = 12 AND price IN (400, 750, 2500, 3750, 5000, 7500)) <> 6 THEN
        RAISE EXCEPTION 'phase-1 store: the launch store packs 1-6 (launch-store.sql) are not all present';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'ultimateteam' AND table_name = 'store_packs'
                   AND column_name = 'banded_odds') THEN
        RAISE EXCEPTION 'phase-1 store: the database has no banded odds yet; start the image with migration 068 first';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'ultimateteam' AND table_name = 'store_packs'
                   AND column_name = 'consumable_mix') THEN
        RAISE EXCEPTION 'phase-1 store: the database has no manager league cards yet; start the image with migration 071 first';
    END IF;
    IF EXISTS (SELECT 1 FROM ultimateteam.store_packs WHERE pack_id IN (8, 9)) THEN
        RAISE EXCEPTION 'phase-1 store: pack 8 or 9 already exists';
    END IF;
END
$$;

-- Bronze and silver: their own tier only; a premium pack's rare slot is one of that tier's in-forms 0.5% of the time. When a
-- pack's manager chance hits, the card is a manager or a manager league card, half each (PLAN 3.8).
UPDATE ultimateteam.store_packs SET banded_odds = true, allowed_currencies = ARRAY['coins'], special_chance = 0, manager_league_card_share = 0.5,
    bio = 'A bronze pack containing 12 bronze items and a chance of a Manager, Manager League card or Chemistry Style.'
WHERE pack_id = 1;
UPDATE ultimateteam.store_packs SET banded_odds = true, allowed_currencies = ARRAY['coins'], special_chance = 0.005, manager_league_card_share = 0.5,
    bio = 'A premium bronze pack containing 12 bronze items with 1 guaranteed rare player and a chance of a Manager, Manager League card or Chemistry Style.'
WHERE pack_id = 4;
UPDATE ultimateteam.store_packs SET banded_odds = true, allowed_currencies = ARRAY['coins'], special_chance = 0, manager_league_card_share = 0.5,
    bio = 'A silver pack containing 12 silver items and a chance of a Manager, Manager League card or Chemistry Style.'
WHERE pack_id = 2;
UPDATE ultimateteam.store_packs SET banded_odds = true, allowed_currencies = ARRAY['coins'], special_chance = 0.005, manager_league_card_share = 0.5,
    bio = 'A premium silver pack containing 12 silver items with 1 guaranteed rare player and a chance of a Manager, Manager League card or Chemistry Style.'
WHERE pack_id = 5;

-- Gold: players only. The Gold Pack is a volume pack (owner, 2026-09-29): gold quick-sells for 360 / 700, so it returns ~93% of
-- its price; its rare slot draws the thinner volume table (rules/pack_odds.json goldRareBandTables) with a 0.4% in-form chance,
-- so every highlight costs more net coins from it than from Premium Gold.
UPDATE ultimateteam.store_packs SET banded_odds = true, allowed_currencies = ARRAY['coins'], special_chance = 0.004,
    odds_table = 'volume', manager_chance = 0, chem_style_chance = 0,
    bio = '12 gold players with 1 guaranteed rare. Players only.'
WHERE pack_id = 3;
UPDATE ultimateteam.store_packs SET banded_odds = true, allowed_currencies = ARRAY['coins'], special_chance = 0.011,
    manager_chance = 0, chem_style_chance = 0,
    bio = '12 gold players with 3 guaranteed rares. Players only.'
WHERE pack_id = 6;

-- The Rare Gold Pack starts as a copy of Premium Gold, so every other column matches the store's gold packs.
CREATE TEMP TABLE phase1_rare_gold ON COMMIT DROP AS
    SELECT * FROM ultimateteam.store_packs WHERE pack_id = 6;
UPDATE phase1_rare_gold SET pack_id = 8, name = 'Rare Gold Pack', price = 25000, points_price = NULL, rare_slots = 12,
    always_present = false, bio = '12 rare gold players. Players only.';
INSERT INTO ultimateteam.store_packs SELECT * FROM phase1_rare_gold;

-- The Consumables Pack (owner, 2026-09-29; PLAN 3.8): 12 distinct consumables, 4 manager league cards, 4 position modifiers
-- and 4 chemistry styles (never Basic). The manager league cards are generated definitions (migration 071), not FIFA data.
INSERT INTO ultimateteam.store_packs(pack_id, kind, enabled, name, bio, price, allowed_currencies, size, random_consumable_count,
    consumable_mix, store_group, always_present, display_only)
VALUES (9, 'store', true, 'Consumables Pack', '12 consumables: manager league cards, position modifiers and chemistry styles.', 3000,
    ARRAY['coins'], 12, 12, '{"manager_league": 4, "position_modifier": 4, "chemistry_style": 4}', 'special', false, false);

COMMIT;

-- What the store sells now.
SELECT pack_id, name, price, rare_slots, special_chance, manager_chance, manager_league_card_share, chem_style_chance, banded_odds,
       consumable_mix, allowed_currencies,
       coalesce(store_group, '(by tier)') AS tab
FROM ultimateteam.store_packs WHERE kind = 'store' AND NOT admin_only ORDER BY pack_id;
