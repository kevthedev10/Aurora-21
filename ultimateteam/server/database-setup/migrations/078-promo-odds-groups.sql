-- Promo odds metadata. These values are stored once per promo and reused by packs and schedules.
-- No draw reads them yet. Existing cards share one weight-1 card group per promo until curated.
ALTER TABLE ultimateteam.promos
    ADD COLUMN odds_category text NOT NULL DEFAULT 'other_promo',
    ADD COLUMN draw_weight numeric(12,6) NOT NULL DEFAULT 1,
    ADD CONSTRAINT promos_odds_category CHECK (odds_category ~ '^[a-z][a-z0-9_]*$'),
    ADD CONSTRAINT promos_draw_weight CHECK (draw_weight > 0);

-- Keep the main headline categories distinct. Other promos can be assigned a more specific
-- category when their pack odds are configured; this migration does not change availability.
SELECT set_config('ultimateteam.content_publish', 'on', true);
UPDATE ultimateteam.promos SET odds_category = CASE
    WHEN code ~ '^totw_[0-9]+$' OR code = 'silver_totw' THEN 'totw'
    WHEN code IN ('team_of_the_year', 'toty_12th_man') THEN 'toty'
    WHEN code LIKE 'toty_honourable_mentions_%' THEN 'toty_honourable_mentions'
    WHEN code = 'base_icons' THEN 'base_icon'
    WHEN code = 'mid_icons' THEN 'mid_icon'
    WHEN code = 'prime_icons' THEN 'prime_icon'
    WHEN code = 'prime_icon_moments' THEN 'icon_moments'
    ELSE odds_category END;
SELECT set_config('ultimateteam.content_publish', '', true);

CREATE TABLE ultimateteam.promo_card_weight_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promo_id bigint NOT NULL REFERENCES ultimateteam.promos(promo_id),
    code text NOT NULL CHECK (code ~ '^[a-z][a-z0-9_]*$'),
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
    draw_weight numeric(12,6) NOT NULL DEFAULT 1 CHECK (draw_weight > 0),
    CONSTRAINT promo_card_weight_groups_code UNIQUE (promo_id, code),
    CONSTRAINT promo_card_weight_groups_promo_id_id UNIQUE (promo_id, id)
);

INSERT INTO ultimateteam.promo_card_weight_groups(promo_id, code, name)
SELECT promo_id, 'default', 'Default' FROM ultimateteam.promos;

ALTER TABLE ultimateteam.promo_cards ADD COLUMN weight_group_id bigint;
SELECT set_config('ultimateteam.content_publish', 'on', true);
UPDATE ultimateteam.promo_cards card SET weight_group_id = grp.id
FROM ultimateteam.promo_card_weight_groups grp
WHERE grp.promo_id = card.promo_id AND grp.code = 'default';
SELECT set_config('ultimateteam.content_publish', '', true);
ALTER TABLE ultimateteam.promo_cards
    ALTER COLUMN weight_group_id SET NOT NULL,
    ADD CONSTRAINT promo_cards_weight_group_same_promo FOREIGN KEY (promo_id, weight_group_id)
        REFERENCES ultimateteam.promo_card_weight_groups(promo_id, id);

CREATE TRIGGER promo_card_weight_groups_publish_guard
    BEFORE UPDATE OR DELETE ON ultimateteam.promo_card_weight_groups
    FOR EACH ROW EXECUTE FUNCTION ultimateteam.lfv4_r2_catalog();

