-- Custom player heads (ultimateteam/live-content-editing-plan.md, step 5): portraits an operator uploads in the panel's
-- card editor, kept as an option for that player (native_asset_id) that any of the player's cards can use. png is the
-- panel's preview; dds is what FIFA 21 reads, 180 x 180 DXT5 with one mip level like the heads in
-- runtime-source/ultimateteam21/custom-playerheads. Rows are never changed or removed once stored: a card that uses one
-- keeps working, and an unused one is simply not offered for new edits.
CREATE TABLE IF NOT EXISTS ultimateteam.custom_player_heads (
    head_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    native_asset_id bigint NOT NULL CHECK (native_asset_id > 0),
    label text NOT NULL CHECK (length(label) BETWEEN 1 AND 80),
    png bytea NOT NULL CHECK (length(png) BETWEEN 8 AND 1048576),
    dds bytea NOT NULL CHECK (length(dds) = 32528),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by text CHECK (created_by IS NULL OR length(created_by) <= 64)
);
CREATE INDEX IF NOT EXISTS custom_player_heads_asset ON ultimateteam.custom_player_heads(native_asset_id, head_id);

-- The head a card shows in the game when an operator picked one in the card editor: another card of the same player's
-- dynamic head (head_resource_id), or an uploaded head (custom_head_id). Both null, as for every card this migration
-- finds, keeps the head the card had before. (The older dynamic_image_resource_id column is not read since migration
-- 020 dropped the table that carried it, and stays as it is, so no existing card changes its head.) Changed only through a
-- reviewed content publish, like every catalogue column.
ALTER TABLE ultimateteam.player_card_definitions
    ADD COLUMN IF NOT EXISTS head_resource_id bigint,
    ADD COLUMN IF NOT EXISTS custom_head_id bigint REFERENCES ultimateteam.custom_player_heads(head_id);

