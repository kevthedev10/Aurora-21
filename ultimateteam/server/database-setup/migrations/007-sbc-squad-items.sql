CREATE TABLE ultimateteam.sbc_squad_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 club_id bigint NOT NULL REFERENCES ultimateteam.clubs(id) ON DELETE CASCADE,
 challenge_id bigint NOT NULL,
 slot_index integer NOT NULL CHECK(slot_index>=0),
 native_item_id bigint NOT NULL CHECK(native_item_id>0),
 UNIQUE(club_id,challenge_id,slot_index),
 UNIQUE(club_id,challenge_id,native_item_id)
);
