-- Custom tactics of a Draft run's squad. The Draft squad is not a club squad (it has no squads row), so a
-- tactics save for it was refused with SQUAD_NOT_FOUND. One row per scalar setting (ordinal NULL) or list
-- entry (ordinal = the entry's index) of a mentality, with the shape squad_tactic_settings/instructions store.
-- Rows go with their run.
CREATE TABLE IF NOT EXISTS ultimateteam.draft_tactics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL REFERENCES ultimateteam.draft_runs (id) ON DELETE CASCADE,
    mentality text NOT NULL,
    setting_code text NOT NULL,
    ordinal integer CHECK (ordinal >= 0),
    integer_value bigint,
    boolean_value boolean,
    text_value text,
    CONSTRAINT draft_tactics_one_typed_value CHECK (num_nonnulls(integer_value, boolean_value, text_value) = 1),
    CONSTRAINT draft_tactics_list_entry_integer CHECK (ordinal IS NULL OR integer_value IS NOT NULL),
    CONSTRAINT draft_tactics_unique UNIQUE NULLS NOT DISTINCT (run_id, mentality, setting_code, ordinal)
);

