-- Normalize shared native rarity categories; keep tier-specific card type identities.
SET CONSTRAINTS ALL IMMEDIATE;
LOCK TABLE ultimateteam.card_types IN ACCESS EXCLUSIVE MODE;
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM ultimateteam.card_types WHERE native_rareflag IS NULL)
 OR EXISTS(SELECT native_rareflag FROM ultimateteam.card_types WHERE native_rareflag NOT IN(0,1) GROUP BY native_rareflag HAVING count(DISTINCT name)>1) THEN
  RAISE EXCEPTION 'Rarity categories require non-null codes and consistent names';
 END IF;
END $$;
CREATE TABLE ultimateteam.native_rarities (
 native_rarity_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 native_rareflag bigint NOT NULL UNIQUE CHECK(native_rareflag>=0),
 name text NOT NULL CHECK(length(trim(name))>0)
);
INSERT INTO ultimateteam.native_rarities(native_rareflag,name)
SELECT native_rareflag, CASE native_rareflag WHEN 0 THEN 'Non-Rare' WHEN 1 THEN 'Rare' ELSE min(name) END
FROM ultimateteam.card_types GROUP BY native_rareflag ORDER BY native_rareflag;
ALTER TABLE ultimateteam.card_types ADD COLUMN native_rarity_id bigint;
ALTER TABLE ultimateteam.card_types DISABLE TRIGGER lfv4_trg_r2_card_types;
UPDATE ultimateteam.card_types t SET native_rarity_id=r.native_rarity_id FROM ultimateteam.native_rarities r WHERE r.native_rareflag=t.native_rareflag;
ALTER TABLE ultimateteam.card_types ENABLE TRIGGER lfv4_trg_r2_card_types;
ALTER TABLE ultimateteam.card_types ALTER COLUMN native_rarity_id SET NOT NULL;
ALTER TABLE ultimateteam.card_types ADD CONSTRAINT lfv4_fk_card_types_native_rarity FOREIGN KEY(native_rarity_id) REFERENCES ultimateteam.native_rarities(native_rarity_id);
CREATE INDEX lfv4_idx_card_types_native_rarity ON ultimateteam.card_types(native_rarity_id);
ALTER TABLE ultimateteam.card_types DROP COLUMN native_rareflag, DROP COLUMN name;
CREATE OR REPLACE FUNCTION ultimateteam.lfv4_r8_item_snapshot() RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, ultimateteam
AS $$
DECLARE
    v_id bigint;
    v_snap ultimateteam.market_item_snapshots%ROWTYPE;
    v_listing ultimateteam.market_listings%ROWTYPE;
BEGIN
        IF TG_OP = 'DELETE' THEN v_id := OLD.trade_id; ELSE v_id := NEW.trade_id; END IF;
    SELECT * INTO v_snap FROM ultimateteam.market_item_snapshots WHERE trade_id = v_id;
    IF NOT FOUND THEN RETURN NULL; END IF;
    SELECT * INTO v_listing FROM ultimateteam.market_listings WHERE trade_id = v_snap.trade_id FOR KEY SHARE;
    IF NOT FOUND THEN RETURN NULL; END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM ultimateteam.item_definitions d
        JOIN ultimateteam.player_card_definitions pcd ON pcd.definition_id = d.definition_id
        JOIN ultimateteam.card_types ct ON ct.card_type_id = pcd.card_type_id
        JOIN ultimateteam.native_rarities rarity_ref ON rarity_ref.native_rarity_id=ct.native_rarity_id
        LEFT JOIN ultimateteam.teams team_ref ON team_ref.team_id=pcd.team_id
        LEFT JOIN ultimateteam.leagues league_ref ON league_ref.league_id=pcd.league_id
        LEFT JOIN ultimateteam.nations nation_ref ON nation_ref.nation_id=pcd.nation_id
        WHERE d.definition_id = v_listing.definition_id
          AND v_snap.definition_id = v_listing.definition_id
          AND v_snap.definition_revision = d.revision
          AND v_listing.resource_id IS NOT DISTINCT FROM d.native_resource_id
          AND v_listing.rating = pcd.rating
          AND v_listing.asset_id IS NOT DISTINCT FROM d.native_asset_id
          AND v_listing.nation_id IS NOT DISTINCT FROM nation_ref.native_nation_id
          AND v_listing.league_id IS NOT DISTINCT FROM league_ref.native_league_id
          AND v_listing.team_id IS NOT DISTINCT FROM team_ref.native_team_id
          AND v_listing.preferred_position IS NOT DISTINCT FROM pcd.position
          AND v_listing.rareflag IS NOT DISTINCT FROM rarity_ref.native_rareflag
          AND v_listing.is_special IS NOT DISTINCT FROM ct.is_special
    ) THEN
        PERFORM ultimateteam.lfv4_err('market item snapshot of trade ' || v_snap.trade_id || ' does not agree with its listing and definition');
    END IF;
    RETURN NULL; END
$$;

