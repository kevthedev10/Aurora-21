-- Squad Building Challenges edited in the operator panel (content area sbc_set). The bundled sbc.json stays the base
-- catalogue; a row here replaces the set with the same key (or adds a new set), and a hidden row removes it from the game.
-- New sets keep their creation order (ordinal), which gives them a stable client set id. Replay-safe.
CREATE TABLE IF NOT EXISTS ultimateteam.sbc_sets (
    set_key    text PRIMARY KEY CHECK (set_key ~ '^[A-Za-z0-9_]{1,64}$'),
    definition jsonb NOT NULL CHECK (jsonb_typeof(definition) = 'object'),
    hidden     boolean NOT NULL DEFAULT false,
    ordinal    bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    updated_at timestamptz NOT NULL DEFAULT now()
);
