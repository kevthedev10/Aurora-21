-- General promo availability: schedules select existing promos; ordinary bronze/silver/gold
-- and Base Icons are always available separately. The initial live window is TOTW 1-3.
CREATE TABLE ultimateteam.promo_schedules (
    schedule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]*$'),
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
    enabled boolean NOT NULL DEFAULT false,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    CONSTRAINT promo_schedules_window CHECK (starts_at < ends_at)
);

CREATE TABLE ultimateteam.promo_schedule_groups (
    schedule_id bigint NOT NULL REFERENCES ultimateteam.promo_schedules(schedule_id),
    promo_id bigint NOT NULL REFERENCES ultimateteam.promos(promo_id),
    enabled boolean NOT NULL DEFAULT true,
    CONSTRAINT promo_schedule_groups_primary PRIMARY KEY (schedule_id, promo_id)
);

CREATE TRIGGER promo_schedules_publish_guard BEFORE UPDATE OR DELETE ON ultimateteam.promo_schedules
    FOR EACH ROW EXECUTE FUNCTION ultimateteam.lfv4_r2_catalog();
CREATE TRIGGER promo_schedule_groups_publish_guard BEFORE UPDATE OR DELETE ON ultimateteam.promo_schedule_groups
    FOR EACH ROW EXECUTE FUNCTION ultimateteam.lfv4_r2_catalog();

