CREATE TABLE ultimateteam.icon_rotations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]*$'),
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
    promo_id bigint NOT NULL REFERENCES ultimateteam.promos(promo_id),
    enabled boolean NOT NULL DEFAULT false,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL CHECK (starts_at < ends_at)
);
CREATE TRIGGER icon_rotations_publish_guard BEFORE UPDATE OR DELETE ON ultimateteam.icon_rotations
    FOR EACH ROW EXECUTE FUNCTION ultimateteam.lfv4_r2_catalog();

-- Player definitions and promo identities remain undeletable. Only membership links may be
-- removed inside a reviewed publish; bucket/event/rotation removal is a reversible disable.
CREATE OR REPLACE FUNCTION ultimateteam.lfv4_r2_catalog() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, ultimateteam AS $$
BEGIN
    IF coalesce(current_setting('ultimateteam.content_publish', true), '') <> 'on'
        OR (TG_OP = 'DELETE' AND TG_TABLE_NAME NOT IN ('promo_cards', 'promo_event_promos')) THEN
        PERFORM ultimateteam.lfv4_err('catalog table ' || TG_TABLE_NAME || ' requires a reviewed content publish');
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;

