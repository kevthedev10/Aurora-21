CREATE SEQUENCE ultimateteam.content_revision_sequence;
CREATE TABLE ultimateteam.content_table_revisions (
    table_name text PRIMARY KEY,
    revision bigint NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT now()
);
CREATE FUNCTION ultimateteam.note_content_revision() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = pg_catalog, ultimateteam AS $$
DECLARE rev bigint;
BEGIN
    -- Allocate revisions in commit order, including changes made by another process.
    PERFORM pg_advisory_xact_lock(210094);
    rev := nextval('ultimateteam.content_revision_sequence');
    INSERT INTO ultimateteam.content_table_revisions(table_name,revision,changed_at)
    VALUES(TG_TABLE_NAME,rev,clock_timestamp())
    ON CONFLICT(table_name) DO UPDATE SET revision=excluded.revision,changed_at=excluded.changed_at;
    PERFORM pg_notify('ultimateteam_content', TG_TABLE_NAME);
    RETURN NULL;
END $$;
